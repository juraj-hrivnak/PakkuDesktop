import org.gradle.api.DefaultTask
import org.gradle.api.file.ConfigurableFileCollection
import org.gradle.api.file.DirectoryProperty
import org.gradle.api.provider.Property
import org.gradle.api.tasks.CacheableTask
import org.gradle.api.tasks.Input
import org.gradle.api.tasks.InputFiles
import org.gradle.api.tasks.OutputDirectory
import org.gradle.api.tasks.PathSensitive
import org.gradle.api.tasks.PathSensitivity
import org.gradle.api.tasks.TaskAction
import java.io.File
import java.security.MessageDigest

/**
 * Writes `OfficialPluginDigests` (plugin id → SHA-256 of `plugin.jar`, plus the ids that
 * came from [officialPlugins]) and `PluginBuildMode`
 * into the host's `teksturepako.pakkuDesktop.app.plugins` package.
 *
 * Release builds hash [officialPlugins] only. Other builds also hash [devPlugins], so in-repo
 * plugins such as `:sample-plugin` load under the same allowlist check, without a bypass.
 */
@CacheableTask
abstract class GenerateOfficialPluginDigests : DefaultTask() {
    /** Plugin directories (`pakku-plugin-dir` variant) that ship with the app. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val officialPlugins: ConfigurableFileCollection

    /** Plugin directories allowlisted only in non-release builds. */
    @get:InputFiles
    @get:PathSensitive(PathSensitivity.RELATIVE)
    abstract val devPlugins: ConfigurableFileCollection

    @get:Input
    abstract val releaseBuild: Property<Boolean>

    @get:OutputDirectory
    abstract val outputDirectory: DirectoryProperty

    @TaskAction
    fun generate() {
        val release = releaseBuild.get()
        val officialRoots = officialPlugins.files
        val roots = if (release) officialRoots else officialRoots + devPlugins.files
        val digests = sortedMapOf<String, String>()
        val official = sortedSetOf<String>()
        for (root in roots) {
            for (folder in root.listFiles(File::isDirectory).orEmpty()) {
                val id = manifestId(folder.resolve("manifest.edn"))
                val jar = folder.resolve("plugin.jar")
                check(jar.isFile) { "missing plugin.jar in $folder" }
                check(digests.put(id, sha256Hex(jar)) == null) { "duplicate plugin id '$id' ($folder)" }
                if (root in officialRoots) official += id
            }
        }

        val out = outputDirectory.get().asFile
        out.deleteRecursively()
        val pkg = out.resolve(PACKAGE.replace('.', '/')).apply { mkdirs() }
        pkg.resolve("OfficialPluginDigests.kt").writeText(digestsSource(digests, official))
        pkg.resolve("PluginBuildMode.kt").writeText(buildModeSource(release))
    }

    private fun manifestId(manifest: File): String {
        check(manifest.isFile) { "missing manifest.edn in ${manifest.parentFile}" }
        return ID.find(manifest.readText())?.groupValues?.get(1)
            ?: error("missing :id in $manifest")
    }

    private fun sha256Hex(file: File): String {
        val digest = MessageDigest.getInstance("SHA-256")
        file.inputStream().use { input ->
            val buffer = ByteArray(DEFAULT_BUFFER_SIZE)
            while (true) {
                val read = input.read(buffer)
                if (read < 0) break
                digest.update(buffer, 0, read)
            }
        }
        return digest.digest().joinToString("") { "%02x".format(it) }
    }

    private fun digestsSource(digests: Map<String, String>, official: Set<String>): String {
        val map = if (digests.isEmpty()) {
            "emptyMap()"
        } else {
            digests.entries.joinToString(",\n", "mapOf(\n", ",\n    )") { (id, hex) ->
                "        PluginId(\"$id\") to \"$hex\""
            }
        }
        val set = if (official.isEmpty()) {
            "emptySet()"
        } else {
            official.joinToString(",\n", "setOf(\n", ",\n    )") { id -> "        PluginId(\"$id\")" }
        }
        return """
            |package $PACKAGE
            |
            |import teksturepako.pakkuDesktop.plugin.PluginId
            |
            |/** Plugin id → SHA-256 of the entire plugin.jar, lowercase hex. Generated by Gradle. */
            |object OfficialPluginDigests {
            |    val byId: Map<PluginId, String> = $map
            |
            |    /** Ids declared with `officialPlugin(...)`; loaded with `PluginTrust.Official`. */
            |    val official: Set<PluginId> = $set
            |}
            |""".trimMargin()
    }

    private fun buildModeSource(release: Boolean): String = """
        |package $PACKAGE
        |
        |/** Generated by Gradle from the requested tasks. */
        |object PluginBuildMode {
        |    /**
        |     * True when a packaging task built this binary: only shipped plugins are allowlisted
        |     * and `-Dpakku.plugins.dir` is ignored.
        |     */
        |    const val release: Boolean = $release
        |}
        |""".trimMargin()

    private companion object {
        const val PACKAGE = "teksturepako.pakkuDesktop.app.plugins"
        val ID = Regex(""":id\s+"([^"]+)"""")
    }
}
